#!/usr/bin/env node
// Scans src/templates/<category>/<leaf>/index.tsx and regenerates src/templates/_generated.ts
// Run: pnpm generate:templates
//
// β model (Issue #6):
// - Each template is a self-contained directory at src/templates/<category>/<leaf>/.
// - templateKey = `<category>-<leaf>` (concat per Q6-3-c) — always lowercase.
// - category is the parent dir name, Capitalized (e.g. `corporate` → `Corporate`).
//   Capitalized is the canonical catalog form; `categoryLabel()` lowercases before
//   i18n lookup, so labels still resolve. This is the single rule that keeps the
//   DB category slug consistent (sync reconciles existing rows to this value).

/** Canonical category form: Capitalize the directory name. */
const toCategory = (dir) => dir.charAt(0).toUpperCase() + dir.slice(1);

import { readdirSync, statSync, existsSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const templatesRoot = join(__dirname, '..', 'src', 'templates');
const outputFile = join(templatesRoot, '_generated.ts');

// Top-level entries: skip infra files, only descend into category dirs.
const INFRA_FILES = new Set(['types.ts', 'registry.ts', 'renderComposition.tsx', 'TemplateClientWrapper.tsx', '_generated.ts']);

function isTemplateDir(p) {
  return statSync(p).isDirectory() && existsSync(join(p, 'index.tsx')) && existsSync(join(p, 'template.ts'));
}

// Collect templates: { category, leaf, templateKey, category, importPath }
const templates = [];
const categories = readdirSync(templatesRoot)
  .filter((e) => !INFRA_FILES.has(e))
  .filter((e) => {
    const full = join(templatesRoot, e);
    return statSync(full).isDirectory();
  })
  .sort();

for (const category of categories) {
  const categoryDir = join(templatesRoot, category);
  const leafs = readdirSync(categoryDir)
    .filter((leaf) => isTemplateDir(join(categoryDir, leaf)))
    .sort();
  for (const leaf of leafs) {
    templates.push({
      category,
      leaf,
      templateKey: `${category}-${leaf}`,
      importPath: `./${category}/${leaf}`,
    });
  }
}

const lines = [
  `// AUTO-GENERATED by \`pnpm generate:templates\` — DO NOT EDIT`,
  `// Re-run: pnpm generate:templates`,
  `import type { TemplateModule, TemplatePreset } from './types';`,
  ``,
  `export const templateMap: Record<string, () => Promise<TemplateModule>> = {`,
  ...templates.map((t) => `  '${t.templateKey}': () => import('${t.importPath}'),`),
  `} as const;`,
  ``,
  `export const presetMap: Record<string, () => Promise<{ default: TemplatePreset }>> = {`,
  ...templates.map((t) => `  '${t.templateKey}': () => import('${t.importPath}/template'),`),
  `} as const;`,
  ``,
  `export const presetSlugs = [`,
  ...templates.map((t) => `  '${t.templateKey}',`),
  `] as const;`,
  ``,
  `/** Maps templateKey → category (Capitalized parent dir name, source of truth) */`,
  `export const templateCategories: Record<string, string> = {`,
  ...templates.map((t) => `  '${t.templateKey}': '${toCategory(t.category)}',`),
  `} as const;`,
  ``,
  `export function getAvailableTemplateKeys(): string[] {`,
  `  return Object.keys(templateMap);`,
  `}`,
  ``,
  `export function getAvailablePresetKeys(): string[] {`,
  `  return Object.keys(presetMap);`,
  `}`,
  ``,
  `export function isPresetSlug(slug: string): boolean {`,
  `  return (presetSlugs as readonly string[]).includes(slug);`,
  `}`,
  ``,
  `export function getCategoryForTemplate(templateKey: string): string | undefined {`,
  `  return templateCategories[templateKey];`,
  `}`,
  ``,
];

writeFileSync(outputFile, lines.join('\n'), 'utf-8');
// Count categories that actually yielded a template — `categories` is every
// top-level dir, which includes non-category ones like `__tests__` that
// contribute no leaf. Deriving from `templates` needs no skip-list upkeep.
const categoryCount = new Set(templates.map((t) => t.category)).size;
console.log(`generate:templates — wrote ${templates.length} templates across ${categoryCount} categories.`);
